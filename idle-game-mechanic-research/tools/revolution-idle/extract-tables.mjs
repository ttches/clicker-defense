/* ============================ circles.csv ============================ */
// Parse the verbatim wiki table: strip {{Keyword|...|Name}} and inline style
// attrs, then read name || cost || multiplier || base lap speed.
function parseCircles(table) {
  const rows = [];
  for (const raw of table.split("\n")) {
    const cleaned = raw
      .replace(/\{\{Keyword\|[^|]*\|([^}]+)\}\}/g, "$1")
      .replace(/style="[^"]*"/g, "");
    const cells = cleaned.split("|").map((s) => s.trim()).filter((s) => s !== "");
    if (cells.length !== 4) continue;
    const [name, cost, mult, speed] = cells;
    if (!Number.isFinite(parseNum(cost))) continue;
    rows.push({
      order: rows.length + 1,
      name,
      initial_cost: fmtNumber(parseNum(cost)),
      cost_multiplier: String(parseNum(mult)),
      base_lap_speed: String(parseNum(speed)),
    });
  }
  return rows;
}

