// Transcribe the wiki milestone table and re-derive every derived column.
function parseMilestones(table) {
  const out = [];
  for (const raw of table.split("\n")) {
    const cells = raw.split("|").map((s) => s.trim()).filter((s) => s !== "");
    if (cells.length !== 7) continue;
    const [level, p1, p2, p3, p4, expTotal, multNeeded] = cells;
    out.push({
      level: Number(level),
      p1_mult_gain: p1,
      p2_lap_speed: Number(p2),
      p3_ascension_power: Number(p3),
      p4_promotion_power: Number(p4),
      exp_total: parseNum(expTotal),
      p_mult_needed: parseNum(multNeeded),
    });
  }
  return out;
}

const milestoneRows = parseMilestones(PROMOTION_MILESTONES);
if (milestoneRows.length !== 21) throw new Error(`expected 21 milestone rows, parsed ${milestoneRows.length}`);

const milestoneCsv = milestoneRows.map((m) => {
  const L = m.level;
  const expTotalCalc = Math.round(Math.pow(2, L) - 1);
  const multNeededCalc = 1000 * Math.pow(expTotalCalc, 4 / 3);
  const p1Calc = Math.floor(Math.pow(L, 1.5)) + 1;
  const p2Calc = round(1 + Math.sqrt(L) / 2, 3);
  const p3Calc = round(10 + Math.pow(L, 0.8) / 2, 2);
  const p4Calc = round(1 + 0.05 * Math.pow(L, 0.48), 3);
  const relErr = m.p_mult_needed === 0 ? 0 : Math.abs(multNeededCalc - m.p_mult_needed) / m.p_mult_needed;
  return {
    level: L,
    p1_mult_gain: m.p1_mult_gain,
    p2_lap_speed: m.p2_lap_speed,
    p3_ascension_power: m.p3_ascension_power,
    p4_promotion_power: m.p4_promotion_power,
    exp_total: String(m.exp_total),
    p_mult_needed: fmtNumber(m.p_mult_needed),
    p1_calc: String(p1Calc),
    p2_calc: String(p2Calc),
    p3_calc: String(p3Calc),
    p4_calc: String(p4Calc),
    exp_total_calc: String(expTotalCalc),
    p_mult_needed_calc: fmtNumber(multNeededCalc),
    p_mult_needed_rel_err: relErr < 5e-3 ? "0" : String(Number(relErr.toPrecision(3))),
    source: SOURCE.rev,
  };
});
