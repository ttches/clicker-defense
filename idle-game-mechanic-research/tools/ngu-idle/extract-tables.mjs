/* ------------------------------------------------------------------ *
 * Template helpers — the wiki infoboxes are newline-delimited |key=value.
 * ------------------------------------------------------------------ */
function extractTemplate(text, names) {
  for (const name of names) {
    const idx = text.indexOf("{{" + name);
    if (idx < 0) continue;
    let depth = 0;
    for (let j = idx; j < text.length - 1; j++) {
      if (text[j] === "{" && text[j + 1] === "{") { depth++; j++; }
      else if (text[j] === "}" && text[j + 1] === "}") { depth--; j++; if (depth === 0) return text.slice(idx + 2, j - 1); }
    }
  }
  return null;
}

// Split the infobox on `|` at brace/bracket depth 0 only, so that a nested
// `{{BigNum|...}}` or `[[link|text]]` pipe is not mistaken for a parameter
// separator. Several wiki lines pack two params together (e.g.
// `|hp=5.02E+33|bf_number=233`); a naive per-line regex lets the trailing
// `|key=value` bleed into the value of the first param.
function parseParams(block) {
  const segments = [];
  let buf = "";
  let curly = 0;
  let square = 0;
  for (let i = 0; i < block.length; i++) {
    const c = block[i];
    const d = block[i + 1];
    if (c === "{" && d === "{") { curly++; buf += c; continue; }
    if (c === "}" && d === "}") { curly = Math.max(0, curly - 1); buf += c; continue; }
    if (c === "[" && d === "[") { square++; buf += c; continue; }
    if (c === "]" && d === "]") { square = Math.max(0, square - 1); buf += c; continue; }
    if (c === "|" && curly === 0 && square === 0) { segments.push(buf); buf = ""; continue; }
    buf += c;
  }
  segments.push(buf);

  const p = {};
  for (const seg of segments) {
    const m = seg.match(/^\s*([A-Za-z0-9_]+)\s*=\s*([\s\S]*?)\s*$/);
    if (m) p[m[1]] = m[2];
  }
  return p;
}

// {{BigNum|VALUE|3}} -> VALUE, resolving the page's simple `{{#expr:A*B^C}}`.
function bigNumValues(line) {
  const out = [];
  const re = /\{\{BigNum\|(.+?)\|3\}\}/g;
  let m;
  while ((m = re.exec(line))) {
    let v = m[1];
    const e = v.match(/\{\{#expr:(.+?)\}\}/);
    out.push(evalBossExpr(e ? e[1] : v));
  }
  return out;
}

/* ============================ items.csv ============================ */
// Artifact lane: evaluate the datamined Items.js exactly as gear-optimizer does
// (ItemAux.Item constructor), then flatten to one row per (item, stat).
function loadItems() {
  const raw = readRef("Items.js");
  const code = raw.replace(/^import[^\n]*\n/, "").replace(/\bexport\s+/g, "");
  const ctx = { Item, EmptySlot, Slot, Stat, SetName, console };
  vm.createContext(ctx);
  new vm.Script(code + "\n;globalThis.__ITEMS = ITEMLIST;").runInContext(ctx);
  return ctx.__ITEMS;
}

const itemsAll = loadItems();
const itemRows = [];
for (const it of itemsAll) {
  if (it.empty) continue;
  const zone = it.zone || [];
  for (const statName of it.statnames) {
    itemRows.push({
      id: it.id,
      name: it.name,
      slot: it.slot[0],
      set: zone[0],
      zone_index: zone[1],
      titan_version: zone.length > 2 ? zone[2] : "",
      stat: statName,
      base_value: it.base[statName],
      item_level: it.level,
      scaled_value: it[statName],
      source: PROV.items,
    });
  }
}
write("items.csv", itemRows,
  ["id", "name", "slot", "set", "zone_index", "titan_version", "stat", "base_value", "item_level", "scaled_value", "source"],
  prov(`items.csv — ${itemRows.length} stat lines across ${new Set(itemRows.map((r) => r.id)).size} items with stats (${itemsAll.filter((x) => !x.empty).length} datamined entries) from the gear-optimizer DB (Items.js sha256 ${GEAROPT.sha256.slice(0, 12)}…)`));

/* =========================== enemies.csv =========================== */
// Transcribe the per-enemy {{Enemy}} infoboxes (Adventure Mode stats).
const enemiesRaw = readRefJson("enemies_raw.json");
const enemyRows = [];
const bossByNumber = new Map();
for (const [title, text] of Object.entries(enemiesRaw)) {
  const block = extractTemplate(text, ["Enemy"]);
  if (!block) continue;
  const p = parseParams(block);
  const hasAdv = p.power !== undefined || p.toughness !== undefined;
  const hasBf = p.bf_power !== undefined || p.bf_toughness !== undefined;
  if (!hasAdv && !hasBf) continue;
  if (hasAdv) {
    enemyRows.push({
      name: title,
      location: p.location || "",
      type: p.type || "",
      attack_rate: p.attack_rate || "",
      power: p.power || "",
      toughness: p.toughness || "",
      hp: p.hp || "",
      hp_regen: p.hp_regen || "",
      bestiary: p.bestiary || "",
      has_boss_fight: hasBf ? "yes" : "",
      source: PROV.enemyPage,
    });
  }
  if (hasBf) {
    const n = Number(p.bf_number);
    bossByNumber.set(n, {
      boss: n,
      name: title,
      attack: parseNum(p.bf_power),
      defense: parseNum(p.bf_toughness),
      hp: parseNum(p.bf_hp),
      hp_regen: parseNum(p.bf_hp_regen),
      exp: p.bf_exp !== undefined ? p.bf_exp : "",
    });
  }
}
enemyRows.sort((a, b) => a.name.localeCompare(b.name));
write("enemies.csv", enemyRows,
  ["name", "location", "type", "attack_rate", "power", "toughness", "hp", "hp_regen", "bestiary", "has_boss_fight", "source"],
  prov(`enemies.csv — ${enemyRows.length} Adventure Mode enemies from per-page {{Enemy}} infoboxes`));

/* ============================ bosses.csv =========================== */
// Boss rows come from the bf_* fields of the same {{Enemy}} infoboxes; the
// ladder expectation is re-derived from the Boss_Fights page's anchors + rule.
const anchorByN = new Map(BOSS_ANCHORS.map((a) => [a.boss, a]));
const base4 = anchorByN.get(4); // 13e5 / 7e5 / 13e6

// Boss_Fights wikitext: pages own literal/`#expr` stats for bosses 1-22.
const bossWiki = readRef("Boss_Fights.wiki").split("\n");
const pageStats = new Map();
for (let i = 0; i < bossWiki.length; i++) {
  const vm2 = bossWiki[i].match(/\{\{Vanchor\|(\d+)\}\}/);
  if (!vm2) continue;
  const n = Number(vm2[1]);
  for (let k = i + 1; k < Math.min(i + 4, bossWiki.length); k++) {
    if (bossWiki[k].includes("{{BigNum")) {
      const v = bigNumValues(bossWiki[k]);
      if (v.length === 3) pageStats.set(n, v);
      break;
    }
  }
}

function ladderExpected(n) {
  const a = anchorByN.get(n);
  if (a) return [a.attack, a.defense, a.hp];
  const { baseBoss, mult5Through, x5, x10 } = BOSS_RULE;
  const exp = n <= mult5Through ? n - baseBoss : mult5Through - baseBoss;
  const over = n <= mult5Through ? 0 : n - mult5Through;
  const f = Math.pow(x5, exp) * Math.pow(x10, over);
  return [base4.attack * f, base4.defense * f, base4.hp * f];
}

const bossRows = [...bossByNumber.values()].sort((a, b) => a.boss - b.boss).map((b) => {
  const [ea, ed, eh] = ladderExpected(b.boss);
  const ps = pageStats.get(b.boss);
  const match = (v, e) => closeTo(v, e, 0.01);
  const pageMatch = ps ? (match(ps[0], b.attack) && match(ps[1], b.defense) && match(ps[2], b.hp)) : "";
  return {
    boss: b.boss,
    name: b.name,
    attack: fmtNumber(b.attack),
    defense: fmtNumber(b.defense),
    hp: fmtNumber(b.hp),
    hp_regen: fmtNumber(b.hp_regen),
    hp_is_10x_attack: closeTo(b.hp, 10 * b.attack, 1e-6) ? "yes" : "no",
    ladder_expected_attack: fmtNumber(ea),
    ladder_expected_defense: fmtNumber(ed),
    ladder_expected_hp: fmtNumber(eh),
    ladder_match: match(b.attack, ea) && match(b.defense, ed) && match(b.hp, eh) ? "yes" : "no",
    page_attack: ps ? fmtNumber(ps[0]) : "",
    page_defense: ps ? fmtNumber(ps[1]) : "",
    page_hp: ps ? fmtNumber(ps[2]) : "",
    page_matches_row: pageMatch,
    source: PROV.bossPage + ";" + PROV.enemyPage,
  };
});
write("bosses.csv", bossRows,
  ["boss", "name", "attack", "defense", "hp", "hp_regen", "hp_is_10x_attack", "ladder_expected_attack",
    "ladder_expected_defense", "ladder_expected_hp", "ladder_match", "page_attack", "page_defense", "page_hp",
    "page_matches_row", "source"],
  prov(`bosses.csv — ${bossRows.length} boss fights sourced from {{Enemy}} bf_* infoboxes; ladder expectation re-derived from Boss_Fights anchors + x5/x10 rule`));

